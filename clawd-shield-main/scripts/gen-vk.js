// converts snarkjs verification_key.json -> programs/clawd_shield/src/vk.rs (big-endian, G2 limbs c1,c0)
const fs=require('fs');const vk=JSON.parse(fs.readFileSync(__dirname+'/../build/verification_key.json'));
const be=x=>BigInt(x).toString(16).padStart(64,'0');
const hex=h=>h.match(/../g).map(b=>'0x'+b).join(',');
const g1=p=>`[${hex(be(p[0])+be(p[1]))}]`;
const g2=p=>`[${hex(be(p[0][1])+be(p[0][0])+be(p[1][1])+be(p[1][0]))}]`;
let s=`// AUTO-GENERATED by scripts/gen-vk.js from a DEV trusted setup (NOT a ceremony). Do not edit.
use groth16_solana::groth16::Groth16Verifyingkey;
pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};
pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${g1(vk.vk_alpha_1)},
    vk_beta_g2: ${g2(vk.vk_beta_2)},
    vk_gamme_g2: ${g2(vk.vk_gamma_2)},
    vk_delta_g2: ${g2(vk.vk_delta_2)},
    vk_ic: &[${vk.IC.map(g1).join(',\n')}],
};
`;fs.writeFileSync(__dirname+'/../programs/clawd_shield/src/vk.rs',s);console.log('nPublic',vk.nPublic,'IC',vk.IC.length);
